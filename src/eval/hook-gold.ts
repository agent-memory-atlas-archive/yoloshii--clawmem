/**
 * Hook replay-eval — labeled replay-set schema + strict loader (BUILD-0,
 * RANKING-DEFECT-HANDOFF Addendum 5 / CONTRACT-5b).
 *
 * A hook replay case freezes ONE UserPromptSubmit situation: the current
 * prompt, the prior-turn window (seeded into `context_usage` at replay time so
 * the real multi-turn lookback runs), and the profile — plus judged labels:
 * per-document must-include / acceptable / must-not-include, the prior-leg
 * decision (required / harmless / forbidden), and whether the correct behavior
 * is to abstain entirely.
 *
 * Same strictness discipline as the query-mode gold loader (`gold.ts`): any
 * malformed line, unknown field, duplicate id, or label contradiction fails
 * the whole load — a silently dropped or misread case corrupts the metric.
 *
 * Expansion outputs are NOT stored in the case: per the cleared design they
 * are REGENERATED by the real pipeline for each input shape at replay time
 * (current-only / conditional-prior / no-concatenation are properties of the
 * code under test, not of the case).
 */

import { readFileSync } from "fs";

/** Label of the prior-turn-leg decision for this case (CONTRACT-5b). */
export type PriorLegLabel = "required" | "harmless" | "forbidden";

/** Which split the case belongs to (CONTRACT-5b: tuning vs held-out acceptance). */
export type HookSplit = "tuning" | "holdout";

export interface HookPrior {
  /** Prior-turn prompt text, seeded verbatim into context_usage.query_text. */
  text: string;
  /** Age of the prior at replay time, in minutes. >10 puts it outside the lookback window (control cases). */
  age_minutes: number;
}

export interface HookGoldExample {
  id: string;
  /** The current user prompt, replayed verbatim. */
  prompt: string;
  /** Prior turns, newest first. Empty = current-only shape. */
  priors: HookPrior[];
  /** CLAWMEM_PROFILE for this case. */
  profile: "speed" | "balanced" | "deep";
  /** True when the correct behavior is to inject nothing. */
  expect_abstain: boolean;
  /** Judged label of the prior-leg decision. */
  prior_leg: PriorLegLabel;
  labels: {
    /** displayPaths (collection/path) that MUST be injected. */
    must_include: string[];
    /** displayPaths that are fine to inject. */
    acceptable: string[];
    /** displayPaths whose injection is a scored failure. */
    must_not_include: string[];
  };
  split: HookSplit;
  tags: string[];
}

export class HookGoldFileError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "HookGoldFileError";
  }
}

const TOP_KEYS = new Set(["id", "prompt", "priors", "profile", "expect_abstain", "prior_leg", "labels", "split", "tags"]);
const LABEL_KEYS = new Set(["must_include", "acceptable", "must_not_include"]);
const PRIOR_KEYS = new Set(["text", "age_minutes"]);
const PROFILES_ALLOWED = new Set(["speed", "balanced", "deep"]);
const PRIOR_LEG_ALLOWED = new Set(["required", "harmless", "forbidden"]);
const SPLIT_ALLOWED = new Set(["tuning", "holdout"]);

function fail(line: number, msg: string): never {
  throw new HookGoldFileError(`hook gold line ${line}: ${msg}`);
}

function requireStringArray(line: number, field: string, v: unknown): string[] {
  if (!Array.isArray(v) || v.some(x => typeof x !== "string" || x.length === 0)) {
    fail(line, `"${field}" must be an array of non-empty strings`);
  }
  return v as string[];
}

/** Parse + validate one JSONL hook gold file. Throws HookGoldFileError on ANY defect. */
export function parseHookGoldFile(path: string): HookGoldExample[] {
  const raw = readFileSync(path, "utf-8");
  const examples: HookGoldExample[] = [];
  const seenIds = new Set<string>();

  const lines = raw.split("\n");
  for (let i = 0; i < lines.length; i++) {
    const lineNo = i + 1;
    const line = lines[i]!.trim();
    if (!line) continue;

    let parsed: unknown;
    try {
      parsed = JSON.parse(line);
    } catch (e) {
      fail(lineNo, `invalid JSON — ${(e as Error).message}`);
    }
    if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
      fail(lineNo, "each line must be a JSON object");
    }
    const obj = parsed as Record<string, unknown>;

    for (const k of Object.keys(obj)) {
      if (!TOP_KEYS.has(k)) fail(lineNo, `unknown field "${k}" — a typo would silently evaluate a different case`);
    }

    if (typeof obj.id !== "string" || obj.id.length === 0) fail(lineNo, `"id" is required and must be a non-empty string`);
    if (seenIds.has(obj.id)) fail(lineNo, `duplicate id "${obj.id}"`);
    seenIds.add(obj.id);

    if (typeof obj.prompt !== "string" || obj.prompt.trim().length === 0) fail(lineNo, `"prompt" is required and must be a non-empty string`);

    const priors: HookPrior[] = [];
    if (obj.priors !== undefined) {
      if (!Array.isArray(obj.priors)) fail(lineNo, `"priors" must be an array`);
      for (const p of obj.priors) {
        if (typeof p !== "object" || p === null || Array.isArray(p)) fail(lineNo, `each prior must be an object`);
        const po = p as Record<string, unknown>;
        for (const k of Object.keys(po)) {
          if (!PRIOR_KEYS.has(k)) fail(lineNo, `unknown prior field "${k}"`);
        }
        if (typeof po.text !== "string" || po.text.trim().length === 0) fail(lineNo, `prior "text" must be a non-empty string`);
        if (typeof po.age_minutes !== "number" || !Number.isFinite(po.age_minutes) || po.age_minutes < 0) {
          fail(lineNo, `prior "age_minutes" must be a non-negative finite number`);
        }
        priors.push({ text: po.text, age_minutes: po.age_minutes });
      }
    }

    const profile = obj.profile ?? "balanced";
    if (typeof profile !== "string" || !PROFILES_ALLOWED.has(profile)) {
      fail(lineNo, `"profile" must be one of speed|balanced|deep`);
    }

    const expectAbstain = obj.expect_abstain ?? false;
    if (typeof expectAbstain !== "boolean") fail(lineNo, `"expect_abstain" must be a boolean`);

    const priorLeg = obj.prior_leg ?? (priors.length === 0 ? "forbidden" : undefined);
    if (typeof priorLeg !== "string" || !PRIOR_LEG_ALLOWED.has(priorLeg)) {
      fail(lineNo, `"prior_leg" must be one of required|harmless|forbidden (it may only be omitted on a priors-free case, where it defaults to "forbidden")`);
    }

    if (typeof obj.labels !== "object" || obj.labels === null || Array.isArray(obj.labels)) {
      fail(lineNo, `"labels" is required and must be an object`);
    }
    const labelsObj = obj.labels as Record<string, unknown>;
    for (const k of Object.keys(labelsObj)) {
      if (!LABEL_KEYS.has(k)) fail(lineNo, `unknown labels field "${k}"`);
    }
    const mustInclude = labelsObj.must_include === undefined ? [] : requireStringArray(lineNo, "labels.must_include", labelsObj.must_include);
    const acceptable = labelsObj.acceptable === undefined ? [] : requireStringArray(lineNo, "labels.acceptable", labelsObj.acceptable);
    const mustNot = labelsObj.must_not_include === undefined ? [] : requireStringArray(lineNo, "labels.must_not_include", labelsObj.must_not_include);

    // Label sets must be disjoint — one document with two labels is a judgment
    // contradiction, not a tie to resolve silently.
    const all = new Map<string, string>();
    for (const [set, name] of [[mustInclude, "must_include"], [acceptable, "acceptable"], [mustNot, "must_not_include"]] as const) {
      for (const p of set) {
        const prior = all.get(p);
        if (prior) fail(lineNo, `"${p}" is labeled both ${prior} and ${name}`);
        all.set(p, name);
      }
    }

    if (expectAbstain && mustInclude.length > 0) {
      fail(lineNo, `expect_abstain=true contradicts a non-empty must_include list`);
    }

    const split = obj.split;
    if (typeof split !== "string" || !SPLIT_ALLOWED.has(split)) {
      fail(lineNo, `"split" is required and must be "tuning" or "holdout" — an unassigned case would silently leak between the sets`);
    }

    const tags = obj.tags === undefined ? [] : requireStringArray(lineNo, "tags", obj.tags);

    examples.push({
      id: obj.id,
      prompt: obj.prompt,
      priors,
      profile: profile as HookGoldExample["profile"],
      expect_abstain: expectAbstain,
      prior_leg: priorLeg as PriorLegLabel,
      labels: { must_include: mustInclude, acceptable, must_not_include: mustNot },
      split: split as HookSplit,
      tags: [...new Set(tags)],
    });
  }

  if (examples.length === 0) throw new HookGoldFileError(`hook gold file is empty: ${path}`);
  return examples;
}

/**
 * Strictly resolve every labeled displayPath against the replay store(s).
 * `must_include` and `must_not_include` refs that don't resolve to an active
 * document make the case unresolvable (stale label ≠ skippable); `acceptable`
 * refs that don't resolve are REMOVED from the scored label set (an
 * unretrievable doc in the ideal-DCG denominator would depress every nDCG)
 * with a warning.
 *
 * Vault-qualified labels: a `skill:` prefix addresses the secondary vault
 * (resolved against `skillStore`; unresolvable when no secondary snapshot is
 * attached). Unprefixed labels address the general vault. Injected paths are
 * qualified the same way by the runner, so metrics match on vault-qualified
 * identity end to end (SCOPE-ALL-LANES).
 */
export function resolveHookLabels(
  store: { db: import("bun:sqlite").Database },
  examples: HookGoldExample[],
  skillStore?: { db: import("bun:sqlite").Database }
): { example: HookGoldExample; unresolved: string[]; warnings: string[] }[] {
  const resolveOne = (label: string): boolean => {
    let db = store.db;
    let displayPath = label;
    if (label.startsWith("skill:")) {
      if (!skillStore) return false; // secondary label without a secondary snapshot
      db = skillStore.db;
      displayPath = label.slice("skill:".length);
    }
    const rows = db.prepare(
      `SELECT id FROM documents WHERE collection || '/' || path = ? AND active = 1 LIMIT 1`
    ).all(displayPath);
    return rows.length > 0;
  };

  return examples.map(example => {
    const unresolved: string[] = [];
    const warnings: string[] = [];
    for (const p of example.labels.must_include) {
      if (!resolveOne(p)) unresolved.push(`must_include: ${p}`);
    }
    for (const p of example.labels.must_not_include) {
      if (!resolveOne(p)) unresolved.push(`must_not_include: ${p}`);
    }
    // Unresolved acceptable labels are REMOVED from the scored label set, not
    // just warned about — an unretrievable doc in the ideal-DCG denominator
    // would silently depress every nDCG (codex turn-6 STANDARDS-3 / CR-4).
    const resolvedAcceptable: string[] = [];
    for (const p of example.labels.acceptable) {
      if (resolveOne(p)) resolvedAcceptable.push(p);
      else warnings.push(`acceptable label does not resolve (removed from scoring): ${p}`);
    }
    const cleaned: HookGoldExample =
      resolvedAcceptable.length === example.labels.acceptable.length
        ? example
        : { ...example, labels: { ...example.labels, acceptable: resolvedAcceptable } };
    return { example: cleaned, unresolved, warnings };
  });
}
